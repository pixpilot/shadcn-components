const PROVIDER_ICONS: Record<
  string,
  React.ComponentType<{ className?: string }> | undefined
> = {
  google: GoogleIcon,
  linkedin_oidc: LinkedInIcon,
  github: GitHubIcon,
};

/**
 * The mark for a sign-in provider.
 *
 * One registry keeps the sign-in buttons and the account's sign-in-methods list
 * showing the same thing, and a provider with no mark of its own falls back to
 * a generic credential icon rather than rendering nothing.
 */
export function ProviderIcon({ provider, className }: ProviderIconProps) {
  const Icon = PROVIDER_ICONS[provider] ?? KeyRound;
  return <Icon className={className} />;
}
